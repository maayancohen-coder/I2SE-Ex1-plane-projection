"""Data tests: run the program on real volumes, including files that the user brings (TESTING.md, level 7).

Run with:  pytest -m data [--nrrd file.nrrd ...] [--csv planes.csv] -s
"""
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
import pytest

from projection.nrrd_reader import read_nrrd
from projection.plane import Triangle, parse_planes
from projection.projector import FastProjector, ReferenceProjector
from test_projector import random_planes

ROOT = Path(__file__).parent.parent
pytestmark = pytest.mark.data           # every test in this file has the "data" label


def sweep_planes(shape, n):
    """n isosceles triangles that cross the whole volume, tilted a little more each time."""
    sx, sy, sz = shape
    planes = []
    for t in np.linspace(0, 1, n):
        z_top, z_bottom = t * (sz - 1), (1 - t) * (sz - 1)
        # b and c are mirror images around x = sx / 2, so the triangle is isosceles
        planes.append(Triangle((sx / 2, 0, z_top), (0, sy - 1, z_bottom), (sx, sy - 1, z_bottom)))
    return planes


def write_csv(path, planes):
    lines = ["# planes generated by test_user_data.py"]
    for plane in planes:
        lines.append(",".join(f"{v:g}" for v in [*plane.start1, *plane.b, *plane.c]))
    path.write_text("\n".join(lines) + "\n")
    return path


def test_volume_can_be_read(nrrd_path):
    volume = read_nrrd(nrrd_path)
    sx, sy, sz = volume.shape
    print(f"\n{nrrd_path.name}: {sx} x {sy} x {sz}, {volume.dtype}, values {volume.data.min()}..{volume.data.max()}")


def test_fast_equals_reference(nrrd_path):
    volume = read_nrrd(nrrd_path)
    for plane in random_planes(np.random.default_rng(7), 20, size=min(volume.shape)):
        assert np.array_equal(FastProjector().project(volume, plane), ReferenceProjector().project(volume, plane))


def test_performance(nrrd_path):
    volume = read_nrrd(nrrd_path)
    planes = sweep_planes(volume.shape, 50)
    projector = FastProjector()
    projector.project(volume, planes[0])                    # warm-up
    start = time.perf_counter()
    for plane in planes:
        projector.project(volume, plane)
    fps = len(planes) / (time.perf_counter() - start)
    print(f"\n{nrrd_path.name}: {fps:.0f} fps (NFR-1 requires at least 30)")
    assert fps >= 30


def test_demo(nrrd_path, csv_path, tmp_path):
    if csv_path is None:
        csv_path = write_csv(tmp_path / "planes.csv", sweep_planes(read_nrrd(nrrd_path).shape, 20))
    expected_frames = len(parse_planes(csv_path))
    out = tmp_path / "out.mp4"
    result = subprocess.run([sys.executable, str(ROOT / "Ex0.py"), str(nrrd_path), str(csv_path), str(out)],
                            capture_output=True, text=True, timeout=600)
    print("\n" + result.stdout)
    assert result.returncode == 0, result.stdout + result.stderr
    assert f"{expected_frames} frames" in result.stdout
    assert out.exists()
